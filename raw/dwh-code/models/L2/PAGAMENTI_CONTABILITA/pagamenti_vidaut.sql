        {{ custom_to_decimal('T.CCRIM_IMPORTO', 13, 2) }} AS EU_PAGAMENTO,
        T.CCRIM_DESTINAT AS CD_DESTINATARIO,
        T.CCRIM_TIPO_DESTINAT AS TP_DESTINATARIO,
        T.CCRIM_COD_LETTERA AS CD_LETTERA_DESTINATARIO,
        T.CCRIM_ABI_CLI AS CD_ABI_DESTINATARIO,
        T.CCRIM_CAB_CLI AS CD_CAB_DESTINATARIO,
        T.CCRIM_CC_CLI AS CD_CC_DESTINATARIO,
        T.CCRIM_BANK_CODE_CLI AS CD_BANK_CODE_DESTINATARIO,
        T.CCRIM_SUB_NUMBER_CLI AS CD_SUB_NUMBER_DESTINATARIO,
        T.CCRIM_FLAG_CONTR_ANTIRIC AS FL_CONTR_ANTIRICICLAGGIO,
        {{ custom_to_date('T.CCRIM_DATA_CONTR_ANTIRIC') }} AS DT_CONTR_ANTIRICICLAGGIO,
        T.CCRIM_EMISSIONE_AS AS TP_EMISSIONE_ASSEGNO,
        T.CCRIM_FNE_ORIGINE AS CD_ORIGINE_PAGAMENTO,
