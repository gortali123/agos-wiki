        T.CCRIM_CUMULATO AS FL_CUMULATO,
        T.CCRIM_CONTROPARTE_CNT AS CD_CONTROPARTE_CNT,
        T.CCRIM_PRESENTAZIONE AS PR_PRESENTAZIONE,
        T.CCRIM_PROGR_NUOVO_PAG AS PR_NUOVO_PAG_RIEMISSIONE,
        T.CCRIM_CRO AS CD_CRO,
        T.CCRIM_FILIALE AS CD_FILIALE,
        T.CCRIM_SOTTOCAUSALE AS CD_SOTTOCAUSALE,
        T.CCRIM_ID_CARTA AS CD_ID_CARTA,
        T.CCRIM_PRODOTTO_CARTA AS CD_PRODOTTO_CARTA,
        T.CCRIM_CAU_RIFIUTO AS CD_CAU_RIFIUTO,
        T.LASTMODIFIEDDATA AS LASTMODIFIEDDATA
    FROM {{ ref('ccrimbo') }} T
    WHERE T.FL_DELETED = 'N'



