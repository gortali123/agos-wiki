        {{ custom_to_date('T.CCRIM_DATA_PAGAMENTO') }} AS DT_PAGAMENTO,
        {{ custom_to_date('T.CCRIM_DATA_VALUTA') }} AS DT_VALUTA,
        {{ custom_to_date('T.CCRIM_DATA_REG_CONTAB') }} AS DT_REG_CONTABILE,
