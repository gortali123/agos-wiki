        T.CCRIM_PROGRESSIVO AS CD_PAG_VIDAUT,
        T.CCRIM_PROVENIENZA AS TP_PROCEDURA,
        T.CCRIM_NUM_PRATICA AS CD_PRATICA,
        T.CCRIM_TIPO_RECORD AS TP_MOTIVO,
        T.CCRIM_STATO AS CD_STATO,
        T.CCRIM_ATTRIBUTO AS CD_ATTRIBUTO,
        T.CCRIM_BANCA_INTE AS CD_BANCA_INTERNA,
