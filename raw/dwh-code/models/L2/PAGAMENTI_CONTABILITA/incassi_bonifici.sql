SELECT
    bo.CBO_PROGRESSIVO AS PR_BONIFICO,
    {{ custom_to_date('bo.CBO_DATA_CARICAMENTO') }} AS DT_CARICAMENTO,
    bo.CBO_BANCA AS CD_CC_INTERNO,
    bo.CBO_CONTRATTO AS CD_PRATICA,
    bo.CBO_PROCEDURA AS TP_PROCEDURA,
    bo.CBO_RATA AS NM_RATA,
    {{ custom_to_date('bo.CBO_DATA_ATTRIBUZ') }} AS DT_ATTRIBUZIONE,
    bo.CBO_OPE_ATTRIBUZ AS CD_UTENZA_ELAB,
    {{ custom_to_date('bo.CBO_DATA_VALUTA') }} AS DT_VALUTA,
    {{ custom_to_date('bo.CBO_DATA_CONTABILE') }} AS DT_CONTABILE,
    CASE WHEN SUBSTRING(bo.CBO_IBAN_ORD, 1, 2) = 'IT' THEN 'OB' ELSE 'BE' END AS TP_BONIFICO,
    bo.CBO_CAUSALE_ABI AS CD_CAUSALE,
    bo.CBO_NOMINATIVO AS CD_BONIFICO,
    bo.CBO_FLAG AS TP_STATO,
    {{ custom_to_date('bo.CBO_DATA_ORDINE') }} AS DT_ORDINE,
    bo.CBO_PROV_BONIFICO AS CD_PROV_BONIFICO,
    bo.CBO_CAUSALE_INTERNA AS CD_CAUSALE_INTERNA,
    bo.CBO_RATE_SALDATE AS NM_RATE_SALDATE,
    bo.CBO_COD_FISC_ORD AS CD_COD_FISC_ORD,
    bo.CBO_RIFERIM_BANCA AS CD_RIFERIMENTO_BANCA,
    bo.CBO_DESCRIZIONE AS DS_BONIFICO,
    bo.CBO_CLIENTE AS CD_CLIENTE,
    {{ custom_to_decimal('bo.CBO_IMPORTO', 13, 2) }} AS EU_IMPORTO,
    bo.CBO_IBAN_ORD AS CD_IBAN,
    SUBSTRING(bo.CBO_IBAN_ORD, 1, 2) AS CD_PAESE,
    SUBSTRING(bo.CBO_IBAN_ORD, 2, 2) AS CD_CIN,
    bo.CBO_ABI_CLI AS CD_ABI,
    bo.CBO_CAB_CLI AS CD_CAB,
    SUBSTRING(bo.CBO_IBAN_ORD, 16, 12) AS CD_CC_CLIENTE,
    NULL AS CD_TERZO_ORDINANTE, -- WARN: CD_TERZO_ORDINANTE senza sorgente/tipo nel data model
    bo.CBO_BENEF_INDIRIZZO AS CD_INDIRIZZO_BENEF,
    bo.CBO_BENEF_LOCALITA AS CD_LOCALITA_BENEF,
    bo.CBO_ATTRIBUZ_AUTOM AS TP_ATTRIBUZ_AUTOM,
    bo.CBO_TIPO_INCASSO AS TP_INCASSO,
    bo.CBO_NDG_ORD AS CD_NDG_ORD,
    bo.CBO_CRO_INCASSO AS CD_CRO_INCASSO,
    bo.CBO_ID_INCASSO AS CD_ID_INCASSO,
    bo.CBO_CC_POSTALE AS CD_CC_POSTALE,
    {{ custom_to_date('bo.CBO_DATA_ALLIBRAM') }} AS DT_ALLIBRAM,
    bo.CBO_CENTRO_ALLIBRAM AS CBO_CENTRO_ALLIBRAM,
    {{ custom_to_date('bo.CBO_DATA_REG_TEST_INC') }} AS DT_REG_TEST_INC,
    bo.CBO_PROGR_TEST_INC AS PR_TEST_INC,
    bo.CBO_TIPO_CONTO AS CBO_TIPO_CONTO,
    bo.CBO_TIPO_MOV AS CBO_TIPO_MOV,
    bo.CBO_DESCRIZIONE_62 AS DS_62
FROM {{ ref('ccboniset') }} bo
WHERE bo.FL_DELETED = 'N'
