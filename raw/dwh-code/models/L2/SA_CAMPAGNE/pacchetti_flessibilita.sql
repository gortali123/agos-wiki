    H.CD_LIBRERIA_PROGRAMMA_ULTIMO,
    H.CD_PROGRAMMA_ULTIMO,
    H.CD_LIBRERIA_PROGRAMMA_PRECEDENTE,
    H.CD_PROGRAMMA_PRECEDENTE,
    H.LASTMODIFIEDDATA

FROM dedup H