    PMB.EU_INTERESSI_TERZ, PMB.EU_INTERESSI_CONVENZ,
    PMB.EU_SPESE_DILAZ_CONVENZ, PMB.EU_TOT_CONTRIB_DA_INTER,
    PMB.EU_SPESE_RICORRENTI, PMB.EU_SPESE_SMGP, PMB.EU_SPESE_TRASPARENZA,
    PMB.EU_SPESE_EC, PMB.EU_SPESE_BOLLO_EC, PMB.EU_SPESE_RICORRENTI_TOT,
    PMB.CD_MARCA_AUTO AS DS_MARCA,
    PMB.DS_MODELLO_AUTO,

    -- === ACCETTAZIONE_INPUT ===
    AI.CD_ESITO_SCORE_CLI             AS CD_ESITO_PREC,
    AI.FL_GIA_CLIENTE_CLI             AS FL_GIACLIENTE_CLI,
