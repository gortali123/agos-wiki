    AI.EU_TOT_ENTRATE_MENSILI_CLI     AS EU_ENTRATE_MENS_TOT_CLI,
    AI.EU_TOT_ENTRATE_MENSILI_COOB    AS EU_ENTRATE_MENS_TOT_COBLGT,
