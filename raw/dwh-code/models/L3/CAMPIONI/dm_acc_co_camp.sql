    CAST(NULL AS VARCHAR(50))         AS FL_INSOLVENZE_PREC_CRIF_CLI,
    CAST(NULL AS VARCHAR(50))         AS IN_OPERAZ_NON_PERF_CRIF_CLI,
    AI.FL_PROTESTI_CLI,
