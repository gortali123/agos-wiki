        SUM(CASE WHEN RM.RN <= 12 AND RM.FL_ACCODAMENTO = 'Y' THEN 1 ELSE 0 END)   AS NM_RATE_ACCODATE_12M,
        SUM(CASE WHEN RM.FL_ACCODAMENTO = 'Y' THEN 1 ELSE 0 END)                   AS FL_ACCODAMENTO_TOT,
        MIN(CASE WHEN RM.FL_ACCODAMENTO = 'Y' THEN RM.DT_ACCODAMENTO END)          AS DT_FIRST_ACCODAMENTO,
        MAX(CASE WHEN RM.FL_ACCODAMENTO = 'Y' THEN RM.DT_ACCODAMENTO END)          AS DT_LAST_ACCODAMENTO
    FROM (
        SELECT
            CD_PRATICA, TP_PROCEDURA, DT_SCADENZA, NM_RATA, NM_RATA_ORIG,
            DT_ACCODAMENTO, FL_ACCODAMENTO, DT_FINE_VALIDITA,
            ROW_NUMBER() OVER (PARTITION BY CD_PRATICA, TP_PROCEDURA ORDER BY DT_SCADENZA DESC) AS RN
        FROM {{ ref('rate_pratica') }}
    ) RM
    GROUP BY RM.CD_PRATICA, RM.TP_PROCEDURA
) ACR
    ON ACR.CD_PRATICA = K.CD_PRATICA AND ACR.TP_PROCEDURA = K.TP_PROCEDURA

