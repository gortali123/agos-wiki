    SELECT
        CD_PRATICA, TP_PROCEDURA, DT_OSSERVAZIONE, CD_CLIENTE, CD_COOBLIGATO,
        CD_ABI, CD_CAB, CD_CANALE_ACQUISIZIONE, CD_STATO,
        DT_CHIUSURA_EFFETTIVA, DT_DBT, DT_DECORRENZA, DT_PASSAGGIO_PERDITA,
        DT_CESSIONE, DT_PRIMA_SCADENZA, EU_EROGATO, EU_FIDO, FL_FIRMA_DOPPIA,
        DT_CARICAMENTO, DT_LIQUIDAZIONE, DT_ULT_ACCODAMENTO, DT_APPROVAZIONE,
        DT_STORNATA, DT_ESTINZIONE_ANTICIPATA, DT_ULTIMA_SCADENZA, DT_RESPINTA,
        FL_CARTOLARIZZATA,
        CD_MERCATO_1, CD_MERCATO_2, CD_MERCATO_3, CD_MERCATO_4,
        CD_MACRO_PRODOTTO_1, CD_MACRO_PRODOTTO_2, CD_MACRO_PRODOTTO_3, CD_MACRO_PRODOTTO_4,
        CD_DESTINAZIONE_BENE, CD_PRODOTTO, CD_TIPO_PRODOTTO, FL_WEB_CANALE_ACQ,

        SUM(CASE WHEN TP_PROCEDURA = 'CA' AND CD_STATO > 40 AND DT_STORNATA IS NULL
                  AND DT_CESSIONE IS NULL AND DT_PASSAGGIO_PERDITA IS NULL AND DT_LIQUIDAZIONE IS NOT NULL
             THEN 1 ELSE 0 END) OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS NM_CONTRATTI_ATTIVI_CARTA,
        SUM(CASE WHEN TP_PROCEDURA = 'CO' AND CD_STATO > 40 AND DT_STORNATA IS NULL
                  AND DT_CESSIONE IS NULL AND DT_PASSAGGIO_PERDITA IS NULL AND DT_LIQUIDAZIONE IS NOT NULL
             THEN 1 ELSE 0 END) OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS NM_CONTRATTI_ATTIVI_CONSUMO,
        SUM(CASE WHEN CD_MACRO_PRODOTTO_1 = 'CA' THEN 1 ELSE 0 END) OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS NM_CONTRATTI_CARTA,
        SUM(CASE WHEN CD_MACRO_PRODOTTO_1 = 'CO' THEN 1 ELSE 0 END) OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS NM_CONTRATTI_CONSUMO,
        SUM(CASE WHEN TP_PROCEDURA = 'CQ'        THEN 1 ELSE 0 END) OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS NM_CQS_CLI,
        {% for m in MESI_RESP %}
        COUNT(CASE WHEN DT_RESPINTA >= ADD_MONTHS(DT_OSSERVAZIONE, -{{ m }}) THEN 1 END)
            OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS _RESP_{{ m }}M_TOT,
        COUNT(CASE WHEN DT_RESPINTA >= ADD_MONTHS(DT_OSSERVAZIONE, -{{ m }}) AND TP_PROCEDURA = 'CA' THEN 1 END)
            OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS _RESP_{{ m }}M_CA,
        COUNT(CASE WHEN DT_RESPINTA >= ADD_MONTHS(DT_OSSERVAZIONE, -{{ m }}) AND TP_PROCEDURA = 'CO' THEN 1 END)
            OVER (PARTITION BY CD_CLIENTE, DT_OSSERVAZIONE) AS _RESP_{{ m }}M_CO{{ "," if not loop.last }}
        {% endfor %}
    FROM {{ ref('pratica_m') }}
    {% if is_incremental() %}
    WHERE DT_OSSERVAZIONE = {{ DT_OSS }}
    {% endif %}
),

