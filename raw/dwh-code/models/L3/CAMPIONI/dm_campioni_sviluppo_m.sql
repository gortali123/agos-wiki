        MAX(CASE WHEN GS.TS_INSERIMENTO = {{ DT_OSS }} THEN GS.NM_GG_SCADUTO_EBA_CLI END) AS NM_MAX_INSOLVENZA_CLI,
        {% for m in MESI_INS %}
        MAX(CASE WHEN GS.TS_INSERIMENTO = ADD_MONTHS({{ DT_OSS }}, -{{ m }}) THEN GS.NM_GG_SCADUTO_EBA_CLI END) AS NM_MAX_INS_CLI_L{{ m }}M{{ "," if not loop.last }}
        {% endfor %}
    FROM {{ ref('giorni_scaduto') }} GS
    WHERE GS.TS_INSERIMENTO IN (
        {{ DT_OSS }}{% for m in MESI_INS %}, ADD_MONTHS({{ DT_OSS }}, -{{ m }}){% endfor %}
    )
    GROUP BY GS.CD_PRATICA, GS.TP_PROCEDURA
) GSH
    ON GSH.CD_PRATICA = K.CD_PRATICA AND GSH.TP_PROCEDURA = K.TP_PROCEDURA